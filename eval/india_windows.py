"""Write reproduce_india.sh from data/cache/manifest_iblend.json.

One line per admissible (series, June) window, so the paper's reproducibility
block can point at a file rather than a paragraph. Run data/iblend.py first.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def kappa_script(m: dict, kappa: float) -> str:
    """The same windows again with the adaptive step stated as a fraction of
    the interval width, into tagged model dirs beside the originals.

    The absolute step every window was trained with is a number in the units
    of the series, and these meters run from 5 kW intervals to 800 kW ones, so
    it is a different layer on every row (eval/aci_step_check.py measures what
    that did to the calibration table). This rerun answers the question the
    horizon-gap result needs: whether the gap between per-step and
    horizon-level exceedance survives a per-step layer whose step transfers.
    Fox is run twice, at both steps, because its original tensor comes from
    the benchmark harness rather than from this trainer and would otherwise
    not be a paired comparison.
    """
    lines = [
        "#!/usr/bin/env bash",
        "# The horizon windows again, with the adaptive-conformal step stated as a",
        f"# fraction ({kappa:g}) of the split-conformal interval width on the validation",
        "# block instead of as an absolute number. Generated by eval/india_windows.py",
        "# --gamma-rel. Run from demand-control/.",
        "set -u",
        "PY=../.venv/bin/python",
        "",
        "# Fox at both steps: its original tensor is the benchmark harness's, so the",
        "# pair has to come from this trainer for the comparison to be paired.",
        "[ -f models/Fox_office_Gaylord@g/forecast_test.parquet ] || "
        "$PY forecast/train.py --buildings Fox_office_Gaylord --tag @g",
        "[ -f results/horizon_risk_Fox_office_Gaylord@g.json ] || "
        "$PY eval/horizon_risk.py --building Fox_office_Gaylord --tag @g --skip-closed-loop",
        "[ -f models/Fox_office_Gaylord@k/forecast_test.parquet ] || "
        f"$PY forecast/train.py --buildings Fox_office_Gaylord --tag @k --adaptive-gamma-rel {kappa:g}",
        "[ -f results/horizon_risk_Fox_office_Gaylord@k.json ] || "
        "$PY eval/horizon_risk.py --building Fox_office_Gaylord --tag @k --skip-closed-loop",
        "",
    ]
    for name, sr in m.items():
        for w in sr["windows"]:
            tag = f"@{w['test_june']}k"
            lines.append(
                f"[ -f models/{name}{tag}/forecast_test.parquet ] || "
                f"$PY forecast/train.py --buildings {name} --tag {tag} --adaptive-gamma-rel {kappa:g} "
                f"--train-start '{w['train_start']}' --train-end '{w['train_end']}' "
                f"--valid-end '{w['valid_end']}' --test-start '{w['test_start']}' --test-end '{w['test_end']}'"
            )
            lines.append(
                f"[ -f results/horizon_risk_{name}{tag}.json ] || "
                f"$PY eval/horizon_risk.py --building {name} --tag {tag} --start '{w['test_start'][:10]}' "
                f"--end '{w['test_end']}' --valid-start '{w['valid_start'][:10]}' --valid-end '{w['valid_end']}' "
                f"--skip-closed-loop"
            )
    lines.append('echo "kappa arm done $(date)"')
    return "\n".join(lines) + "\n"


def main() -> None:
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--gamma-rel", type=float, default=None,
                    help="also write reproduce_india_kappa.sh, the same windows with the "
                         "adaptive step as this fraction of the interval width")
    args = ap.parse_args()
    m = json.loads((ROOT / "data/cache/manifest_iblend.json").read_text())["series"]
    if args.gamma_rel is not None:
        out = ROOT / "reproduce_india_kappa.sh"
        out.write_text(kappa_script(m, args.gamma_rel))
        out.chmod(0o755)
        print(f"wrote {out}")
    lines = [
        "#!/usr/bin/env bash",
        "# India arm. Generated by eval/india_windows.py from data/cache/manifest_iblend.json;",
        "# one line per admissible (series, June) window. Run from demand-control/.",
        "set -u",
        "PY=../.venv/bin/python",
        "",
        "# 1. the benchmark: five forecasters, identical calibration layer, every window",
        "$PY eval/comparative.py --arms india --out comparative_india --skip-done",
        "",
        "# 2. the horizon gap: train the quantile boosters per window, then measure open loop",
    ]
    for name, s in m.items():
        for w in s["windows"]:
            tag = f"@{w['test_june']}"
            # Resumable: a window whose boosters or horizon result already exist is skipped.
            lines.append(
                f"[ -f models/{name}{tag}/forecast_test.parquet ] || "
                f"$PY forecast/train.py --buildings {name} --tag {tag} --train-start '{w['train_start']}' "
                f"--train-end '{w['train_end']}' --valid-end '{w['valid_end']}' "
                f"--test-start '{w['test_start']}' --test-end '{w['test_end']}'"
            )
            lines.append(
                f"[ -f results/horizon_risk_{name}{tag}.json ] || "
                f"$PY eval/horizon_risk.py --building {name} --tag {tag} --start '{w['test_start'][:10]}' "
                f"--end '{w['test_end']}' --valid-start '{w['valid_start'][:10]}' --valid-end '{w['valid_end']}' "
                f"--skip-closed-loop"
            )
    lines += [
        "",
        "# 3. bootstrap intervals on every horizon row. A fresh run above writes them;",
        "#    this attaches them to a result produced before they existed.",
    ]
    for name, s in m.items():
        for w in s["windows"]:
            tag = f"@{w['test_june']}"
            lines.append(
                f"grep -q empirical_horizon_ci results/horizon_risk_{name}{tag}.json || "
                f"$PY eval/horizon_risk.py --building {name} --tag {tag} --ci-only"
            )
    lines += [
        "",
        "# 4. what the copula's one free parameter contributes: likelihood-selected and",
        "#    fixed-from-Phoenix nu against the tail-matched one, every window (resumable)",
        "$PY eval/copula_df_check.py",
    ]
    lines.append('echo "india arm done $(date)"')
    out = ROOT / "reproduce_india.sh"
    out.write_text("\n".join(lines) + "\n")
    out.chmod(0o755)
    print(f"wrote {out} ({sum(len(s['windows']) for s in m.values())} windows)")


if __name__ == "__main__":
    main()
