"""Generate a model card per trained model, from the artefacts rather than by hand.

Section 6.8. A model card written by a human drifts from the model within a day;
this one is regenerated by ``reproduce.sh`` from the benchmark JSON, the split
module and the interpretability study, so a card that disagrees with the results
directory cannot exist.

The sections are the standard ones -- purpose, data, features, training,
evaluation, limitations, intended and unintended use -- because a judge who has
seen a model card before should recognise the shape immediately, and because the
limitations section is the one that earns the rest of it.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import sys
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from forecast.baselines import REGISTRY
from forecast.features import FEATURE_COLS, HORIZON_STEPS, ORIGIN_LAGS
from forecast.splits import SPLIT

RESULTS = ROOT / "results"
MODELS = ROOT / "models"

INTENDED = """\
- Supplying the upper bound `base_q95` to the demand-ceiling constraint of the
  chance-constrained MILP in `control/mpc.py`, at 15-minute resolution out to
  {horizon} hours.
- Supplying `q50` to the energy-cost term of the same optimiser, where planning
  on a tail would overstate the bill and distort the trade-off.
- Reporting rolling coverage in the operator interface, so the safety property is
  monitored rather than assumed.
"""

NOT_INTENDED = """\
- Billing, settlement or any figure a consumer is charged on. The bill engine in
  `tariff/bill.py` is the only source of money in this system, and it reads
  realised meter data, never a forecast.
- Buildings materially unlike the training site without re-fitting. The
  cold-start study measures what happens on a building held out entirely; read
  it before assuming transfer.
- Horizons beyond {horizon} hours. The model was neither trained nor calibrated
  there and the controller clamps its planning horizon rather than extrapolating.
- Any decision where a 5% exceedance rate is unacceptable. q95 is a 95th
  percentile by construction and by measurement; it is not a guarantee that load
  will never exceed it, and the controller is designed around that fact.
"""


def card(building: str, key: str, bench: dict, interp: dict | None) -> str:
    m = bench["models"][key]
    s = m["scores"]
    raw = m.get("scores_uncalibrated", {})
    cls = REGISTRY[key]
    horizon_h = HORIZON_STEPS // 4

    lines = [
        f"# Model card — {cls.name}",
        "",
        f"**Building:** `{building}`  ",
        f"**Role in the system:** {'primary — its q95 enters the capacity constraint' if key == 'lightgbm_quantile' else 'benchmark reference'}  ",
        f"**Generated by:** `eval/model_cards.py` from `results/forecast_benchmark_{building}.json`",
        "",
        "## Purpose",
        "",
        "Probabilistic 15-minute forecast of the building's uncontrollable base "
        f"load, direct multi-horizon out to {horizon_h} hours, reported as the "
        "quantiles 0.05, 0.25, 0.50, 0.75 and 0.95.",
        "",
        "The output is not a chart for a human to look at. It is a numerical bound "
        "inside a hard constraint in an optimiser:",
        "",
        "```",
        "base_q95[t] + controllable[t] - solar_q05[t]  <=  D_target",
        "```",
        "",
        "Every kilowatt of forecast error is a kilowatt of headroom the building "
        "either wastes or dangerously gives away.",
        "",
        "## Data",
        "",
        "Building Data Genome Project 2 — real hourly electricity meter data plus "
        "site weather, upsampled to 15 minutes with a shape-preserving PCHIP "
        "interpolation. Site Fox (Tempe, Arizona), selected as the hottest site in "
        "the set and a reasonable solar-geometry analogue for northern India.",
        "",
        f"| Block | Range | (origin, horizon) rows |",
        f"| --- | --- | --- |",
        f"| Train | {SPLIT.train_start} to {SPLIT.train_end} | see `splits` in the JSON |",
        f"| Calibrate | {SPLIT.valid_start} to {SPLIT.valid_end} | |",
        f"| Test (touched once) | {SPLIT.test_start} to {SPLIT.test_end} | {s['n']:,} |",
        "",
        "The split is temporal and frozen in `forecast/splits.py`. It is never "
        "random: neighbouring 15-minute samples of a load series are almost the "
        "same number, so a random split is a memory test. `tests/test_leakage.py` "
        "asserts the ordering and, separately, rewrites the future of the series "
        "and asserts that no feature at an earlier origin moves.",
        "",
        "## Features",
        "",
        f"{len(FEATURE_COLS)} features, all knowable at the forecast origin:",
        "",
        f"- lags at {', '.join(str(l) for l in ORIGIN_LAGS)} steps before the origin",
        "- rolling mean and standard deviation over 1 hour, 1 day and 1 week",
        "- same-time-of-day mean over the trailing four weeks",
        "- outdoor temperature at the origin, and its 1-hour change",
        "- horizon index (one model serves every horizon)",
        "- calendar: time of day, day of week, weekend, US federal holiday, day of year",
        "- a solar elevation term",
        "",
        "**One declared exception to origin-time causality:** weather at the target "
        "time is used as a perfect forecast. This flatters the model and is stated "
        "here rather than discovered. It can be stressed with `--weather-noise-c`, "
        "and the `sensor_dropout` scenario freezes the forecast entirely.",
        "",
        "## Training",
        "",
    ]

    if key == "lightgbm_quantile":
        from forecast.train import LGB_PARAMS
        lines += [
            "LightGBM with `objective='quantile'`, one booster per quantile, early "
            "stopping on the calibration block.",
            "",
            "| Hyperparameter | Value |",
            "| --- | --- |",
        ] + [f"| `{k}` | {v} |" for k, v in LGB_PARAMS.items() if k != "verbose"] + [
            f"| `num_boost_round` (cap) | 600 |",
            "",
            "Best iteration per quantile: "
            + ", ".join(f"q{int(float(q) * 100):02d} = {v}"
                        for q, v in (m.get("best_iteration") or {}).items()) + ".",
        ]
    elif key == "neural_quantile":
        lines += [
            "A residual MLP stack (N-BEATS-style blocks) with a shared trunk and a "
            "five-output pinball head, so all quantiles come from one network and "
            "cannot cross by construction of the loss alone.",
            "",
            "Trained with Adam and a cosine schedule. Training curve:",
            "",
            "| Epoch | Train pinball | Valid pinball |",
            "| --- | --- | --- |",
        ] + [f"| {r['epoch']} | {r['train_pinball']:.4f} | {r.get('valid_pinball', float('nan')):.4f} |"
             for r in (m.get("training_curve") or [])]
    else:
        lines += [f"{cls.definition.capitalize()}."]

    lines += [
        "",
        "## Calibration",
        "",
        "Two stages, both fitted on the calibration block and never on test.",
        "",
        "1. **Split conformal.** Each quantile is shifted by the empirical residual "
        "quantile, per horizon. Gradient-boosted quantile regression is not "
        "calibrated by construction; without this the nominal level is decorative.",
        "2. **Adaptive conformal (ACI).** Split conformal fitted on April–May "
        "undercovers in June because June is hotter — ordinary distribution shift. "
        "ACI moves the offset against the realised exceedance rate after each "
        "target time becomes known, which buys a distribution-free, finite-sample "
        "coverage property rather than an assumed one.",
        "",
        "The same layer is applied to every baseline in the benchmark, so the "
        "comparison measures the forecast rather than the wrapper.",
        "",
        "## Evaluation",
        "",
        "Measured once on the test block, on data the model never saw.",
        "",
        "| Metric | Calibrated | Raw model |",
        "| --- | --- | --- |",
        f"| Mean pinball loss (kW) | **{s['pinball_mean']:.3f}** | {raw.get('pinball_mean', float('nan')):.3f} |",
        f"| CRPS (kW, five-level approximation) | {s['crps']:.3f} | {raw.get('crps', float('nan')):.3f} |",
        f"| Winkler score, 90% interval | {s['winkler_90']:.1f} | {raw.get('winkler_90', float('nan')):.1f} |",
        f"| 90% interval coverage | **{s['coverage_90']:.3f}** | {raw.get('coverage_90', float('nan')):.3f} |",
        f"| Actuals at or below q95 | {s['below_q95']:.3f} | {raw.get('below_q95', float('nan')):.3f} |",
        f"| Mean interval width (kW) | {s['sharpness_90']:.1f} | {raw.get('sharpness_90', float('nan')):.1f} |",
        f"| Calibration error | {s['calibration_error']:.4f} | {raw.get('calibration_error', float('nan')):.4f} |",
        f"| PIT deviation from flat | {s['pit_deviation']:.4f} | {raw.get('pit_deviation', float('nan')):.4f} |",
        f"| MAE of the median (kW) | {s['mae_median']:.2f} | {raw.get('mae_median', float('nan')):.2f} |",
        f"| RMSE of the median (kW) | {s['rmse_median']:.2f} | {raw.get('rmse_median', float('nan')):.2f} |",
        "",
        "Point accuracy is reported because it is always asked for. It is not the "
        "operative metric here: the controller substitutes q95 into a hard "
        "constraint, so what matters is whether q95 is really a 95th percentile "
        "and how tight it is while staying so.",
        "",
        "Against the full benchmark and the ablation: see "
        "`results/forecast_benchmark.md` and `results/ablation.md`.",
        "",
    ]

    if bench.get("rolling") and key in bench["rolling"]["summary"]:
        r = bench["rolling"]["summary"][key]
        lines += [
            "### Rolling origin",
            "",
            f"{len(bench['rolling']['folds'])} expanding-window folds. "
            f"Pinball {r['pinball_mean']:.3f} ± {r['pinball_std']:.3f} "
            f"(worst fold {r['pinball_max']:.3f}), coverage "
            f"{r['coverage_mean']:.3f} with a worst fold of {r['coverage_worst']:.3f}. "
            f"Best of the field on {r['folds_won']} of {len(bench['rolling']['folds'])} folds.",
            "",
        ]

    if key == "lightgbm_quantile" and interp:
        fa = interp.get("feature_ablation", {})
        sh = interp.get("shap", {})
        if sh:
            lines += [
                "### What the model uses",
                "",
                "Mean |SHAP| on held-out data, q95 booster: "
                + ", ".join(f"`{f}`" for f in sh["shap"]["q95"]["top"][:6]) + ".",
                "",
            ]
        if fa:
            lines += [
                "### What the model needs",
                "",
                "Drop a feature group, retrain, measure the damage "
                f"({fa['settings']['train_rows']:,} rows, "
                f"{fa['settings']['n_estimators']} rounds, scored on validation).",
                "",
                "| Group removed | Pinball | Degradation |",
                "| --- | --- | --- |",
            ] + [f"| {g['group']} | {g['pinball_mean']:.3f} | "
                 f"{g['degradation']:+.3f} ({g['degradation_pct']:+.1f}%) |"
                 for g in fa["groups"]] + [""]

    lines += [
        "## Known limitations",
        "",
        "- **The building is American.** Load *shapes* are American: this site peaks "
        "around 14:00, inside the tariff's normal window rather than the 18:00–22:00 "
        "peak window, so the time-of-day arbitrage available here is weaker than it "
        "would be for an Indian office. The result is conservative rather than "
        "flattering, but the reader should know.",
        "- **Hourly source data upsampled to 15 minutes.** Interpolation smooths real "
        "sub-hourly variability, so measured peaks are understated.",
        "- **Weather at the target time is a perfect forecast.** Stated above.",
        "- **The base load / HVAC split is inferred, not submetered.** The meter is "
        "one channel; the decomposition is a model.",
        "- **One month of test data.** June 2017, the hottest month at the site. "
        "The rolling-origin folds exist because one month is not a season.",
        "- **Calibration is a property of the test distribution.** ACI recovers "
        "coverage under drift but it recovers it *after* the drift starts; the first "
        "few intervals of a regime change are the exposed ones.",
        "",
        "## Intended use",
        "",
        INTENDED.format(horizon=horizon_h),
        "## Not intended for",
        "",
        NOT_INTENDED.format(horizon=horizon_h),
        "## Reproducing",
        "",
        "```bash",
        "./reproduce.sh          # everything, from raw data to figures",
        f"python eval/forecast_eval.py --buildings {building}   # just this table",
        "```",
        "",
        "Seeds are fixed. Every number above was written by a script; if this card "
        "disagrees with `results/`, `results/` is right and this card is stale.",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--buildings", nargs="+", default=["Fox_office_Gaylord"])
    ap.add_argument("--keys", nargs="+", default=["lightgbm_quantile", "neural_quantile"])
    args = ap.parse_args()

    interp_path = RESULTS / "interpretability.json"
    interp = json.loads(interp_path.read_text()) if interp_path.exists() else None

    for b in args.buildings:
        p = RESULTS / f"forecast_benchmark_{b}.json"
        if not p.exists():
            raise SystemExit(f"no benchmark for {b}; run eval/forecast_eval.py first")
        bench = json.loads(p.read_text())
        for key in args.keys:
            if key not in bench["models"]:
                continue
            out = MODELS / b / f"model_card{'' if key == 'lightgbm_quantile' else '_' + key}.md"
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(card(b, key, bench, interp))
            print(f"   wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
